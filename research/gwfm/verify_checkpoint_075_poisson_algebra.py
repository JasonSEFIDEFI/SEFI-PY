#!/usr/bin/env python3
"""
GWFM / SEFI — Checkpoint 075

Classical Poisson algebra of phase-space observables.

Tests:
1. Antisymmetry
2. Bilinearity
3. Leibniz rule
4. Jacobi identity
5. Canonical bracket
6. Commutative multiplication
7. Hamiltonian evolution

No quantum commutation relations are assumed.
"""

import sympy as sp

x, p, m = sp.symbols("x p m", real=True)
m = sp.symbols("m", positive=True, real=True)
a, b = sp.symbols("a b", real=True)

print("=" * 64)
print("GWFM / SEFI — CHECKPOINT 075")
print("CLASSICAL POISSON ALGEBRA")
print("=" * 64)

def PB(f, g):
    return sp.simplify(
        sp.diff(f, x)*sp.diff(g, p)
        - sp.diff(f, p)*sp.diff(g, x)
    )

# Independent polynomial observables.
f = x**2*p + p**3
g = x*p**2 + x**3
h = x**2 + p**2

# 1. Antisymmetry
assert sp.simplify(PB(f,g)+PB(g,f)) == 0
print("PASS: antisymmetry")

# 2. Bilinearity
assert sp.simplify(
    PB(a*f+b*g,h)-a*PB(f,h)-b*PB(g,h)
) == 0
print("PASS: bilinearity")

# 3. Leibniz rule
assert sp.simplify(
    PB(f,g*h)-PB(f,g)*h-g*PB(f,h)
) == 0
print("PASS: Leibniz rule")

# 4. Jacobi identity
jacobi = sp.simplify(
    PB(f,PB(g,h))
    + PB(g,PB(h,f))
    + PB(h,PB(f,g))
)

assert jacobi == 0
print("PASS: Jacobi identity")

# 5. Canonical bracket
assert PB(x,p) == 1
assert PB(p,x) == -1

print("PASS: canonical Poisson bracket")

# 6. Classical observable multiplication
assert sp.simplify(f*g-g*f) == 0
assert sp.simplify(x*p-p*x) == 0

print("PASS: ordinary observable multiplication commutes")

# 7. Relativistic Hamiltonian evolution
H = sp.sqrt(p**2+m**2)

xdot = PB(x,H)
pdot = PB(p,H)

assert sp.simplify(
    xdot-p/sp.sqrt(p**2+m**2)
) == 0

assert pdot == 0

print("PASS: relativistic Hamiltonian evolution")

# 8. Conservation of Hamiltonian
assert PB(H,H) == 0

print("PASS: Hamiltonian conserved")

# 9. Poisson bracket does not equal
# ordinary multiplication commutator.
assert PB(x,p) == 1
assert x*p-p*x == 0

print("PASS: Poisson bracket distinct from")
print("      multiplication commutator")

print("\n" + "=" * 64)
print("CHECKPOINT 075: ALL TESTS PASSED")
print("=" * 64)

print("ESTABLISHED:")
print("- Classical phase-space observables form")
print("  a commutative associative algebra.")
print("- Their Poisson bracket defines a Lie algebra.")
print("- Hamiltonian evolution is generated by")
print("  the Poisson bracket.")

print("\nNOT ESTABLISHED:")
print("- Noncommuting quantum operators.")
print("- Canonical quantum commutation relations.")
print("- Hilbert-space representation.")
print("- The Born rule.")
