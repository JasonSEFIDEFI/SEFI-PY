"""CP098-T37: Independent chi_T preservation audit.

Direct canonical directional derivatives, evaluated
before imposing the regular constrained family.

Internal variables are held fixed because chi_T,
phi_T and phi_N have no internal dependence.

No assumed multiplier solution or closure.
"""

import sympy as sp

eta = sp.diag(-1, 1, 1, 1)

v, k = sp.symbols("v k", positive=True)
a, n, b, c, r, s, x, y = sp.symbols(
    "a n b c r s x y", real=True
)
A, B, C = sp.symbols(
    "A B C", real=True, nonzero=True
)
e = sp.symbols("e", real=True)
LT, LN = sp.symbols("lambda_T lambda_N", real=True)

def dot(X, Y):
    return (X.T * eta * Y)[0]

def pair(p, X):
    return (p.T * X)[0]

def geom(u, q):
    speed = sp.sqrt(-dot(u, u))
    T = u/speed
    tq = dot(T, q)
    w = q + T*tq
    w2 = dot(w, w)
    kap = sp.sqrt(w2)/speed**2
    N = w/sp.sqrt(w2)
    return speed, T, tq, N, kap, w2

def H(u, q, P, p1, p0):
    speed, T, tq, N, kap, w2 = geom(u, q)
    return (
        pair(p0, u)
        + pair(p1, q)
        + speed*(B + A*kap**2)
        - speed*w2*dot(P, P)/(4*C)
    )

def chiT(u, q, p1):
    return pair(p1, geom(u, q)[1])

def phiT(u, q, P):
    return pair(P, geom(u, q)[1])

def phiN(u, q, P):
    return pair(P, geom(u, q)[3])

def derivative(expr):
    return sp.factor(sp.diff(expr, e).subs(e, 0))

u = sp.Matrix([v, 0, 0, 0])
q = sp.Matrix([a, v**2*k, 0, 0])
P = sp.Matrix([0, 0, r, s])
p1 = sp.Matrix([0, -2*A*k/v, x, y])

R = r**2 + s**2
p0 = sp.Matrix([
    A*k**2 + v**4*k**2*R/(4*C) - B,
    n, b, c
])

speed, T, tq, N, kap, w2 = geom(u, q)

print("=== CP098-T37 ===", flush=True)

constraints = {
    "phi_T": phiT(u, q, P),
    "phi_N": phiN(u, q, P),
    "chi_T": chiT(u, q, p1),
    "chi_N": pair(p1, N) + 2*A*kap/speed,
    "psi_T": (
        pair(p0, T) + B - A*kap**2
        - w2*dot(P, P)/(4*C)
    )
}

for name, expression in constraints.items():
    result = sp.factor(expression)
    print(name, "=", result, flush=True)
    assert result == 0, name

print("PASS: five constraints", flush=True)

# Canonical (u,p1) bracket:
# {chiT,H} = chiT_u . H_p1 - chiT_p1 . H_u
# H_p1=q and chiT_p1=T.

print("Calculating {chi_T,Hc}...", flush=True)

term1 = derivative(
    chiT(u + e*q, q, p1)
)

term2 = derivative(
    H(u + e*T, q, P, p1, p0)
)

BH = sp.factor(term1-term2)

print("chiT_u.q =", term1, flush=True)
print("T.H_u =", term2, flush=True)
print("{chi_T,Hc} =", BH, flush=True)

# phiT and phiN are independent of p1.
# chiT is independent of P.
#
# Hence:
# {chiT,phi} = chiT_u . phi_p1
#              - chiT_p1 . phi_u
#              + chiT_q . phi_P
#              - chiT_P . phi_q
#
# Only -T . phi_u remains.

print("Calculating multiplier brackets...", flush=True)

BT = sp.factor(
    -derivative(phiT(u + e*T, q, P))
)

BN = sp.factor(
    -derivative(phiN(u + e*T, q, P))
)

print("{chi_T,phi_T} =", BT, flush=True)
print("{chi_T,phi_N} =", BN, flush=True)

equation = sp.factor(BH + LT*BT + LN*BN)

print("FULL chi_T PRESERVATION EXPRESSION =",
      equation, flush=True)

# Independently verify the displayed expression
# by differentiating the complete total Hamiltonian
# along the canonical direction generated by chiT.
HT = (
    H(u, q, P, p1, p0)
    + LT*phiT(u, q, P)
    + LN*phiN(u, q, P)
)

direct_total = sp.factor(
    derivative(chiT(u + e*q, q, p1))
    - derivative(
        H(u + e*T, q, P, p1, p0)
        + LT*phiT(u + e*T, q, P)
        + LN*phiN(u + e*T, q, P)
    )
)

difference = sp.factor(direct_total-equation)

print("Independent total residual =", difference,
      flush=True)

assert difference == 0

print("PASS: chi_T canonical preservation calculation")
print("MULTIPLIER EQUATION: displayed above")
print("FULL DIRAC CLOSURE: NOT ESTABLISHED")
print("DYNAMICAL CONSISTENCY: OPEN")
