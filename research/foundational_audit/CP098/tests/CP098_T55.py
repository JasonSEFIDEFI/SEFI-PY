"""CP098-T55: Primary-only action symmetry obstruction.

Tests the bulk variation of the canonical total action
under G = epsilon(tau)*phi_T.

Uses the independently verified exact T47 and T40
Poisson identities.

This is a necessary action-level algebraic test,
not a complete variational proof for a general generator.
"""

import sympy as sp

eps, epsdot = sp.symbols(
    "epsilon epsilon_dot", real=True
)
dLT, dLN = sp.symbols(
    "delta_lambda_T delta_lambda_N", real=True
)

v, k = sp.symbols("v k", positive=True)
phiT, phiN, chiT = sp.symbols(
    "phi_T phi_N chi_T", real=True
)

print("=== CP098-T55 ===", flush=True)

# From T47:
# {phi_T,Hc} = -chi_T + v*k*phi_N
#
# From T40:
# {phi_T,phi_T} = {phi_T,phi_N} = 0
#
# Thus {G,H_T} = eps*(-chiT+v*k*phiN).

explicit_time = epsdot*phiT
hamiltonian_bracket = eps*(-chiT+v*k*phiN)
multiplier_variation = -dLT*phiT-dLN*phiN

bulk = sp.expand(
    explicit_time
    + hamiltonian_bracket
    + multiplier_variation
)

expected = (
    (epsdot-dLT)*phiT
    +(eps*v*k-dLN)*phiN
    -eps*chiT
)

assert sp.expand(bulk-expected) == 0

print("Bulk action variation =", bulk, flush=True)
print("PASS: primary-only variation identity",
      flush=True)

# Permit completely arbitrary variations of both
# primary multipliers, but not additional
# transformations generated by secondary constraints.

coeff_phiT = sp.diff(bulk,phiT)
coeff_phiN = sp.diff(bulk,phiN)
coeff_chiT = sp.diff(bulk,chiT)

print("Coefficient phi_T =", coeff_phiT, flush=True)
print("Coefficient phi_N =", coeff_phiN, flush=True)
print("Coefficient chi_T =", coeff_chiT, flush=True)

assert sp.simplify(coeff_phiT-(epsdot-dLT)) == 0
assert sp.simplify(coeff_phiN-(eps*v*k-dLN)) == 0
assert sp.simplify(coeff_chiT+eps) == 0

print("PASS: independent constraint coefficients",
      flush=True)

# Cancel the primary-constraint coefficients.
primary_cancellation = {
    dLT: epsdot,
    dLN: eps*v*k
}

remaining = sp.factor(
    bulk.subs(primary_cancellation)
)

print("After primary multiplier cancellation =",
      remaining, flush=True)

assert sp.factor(remaining+eps*chiT) == 0

# The secondary coefficient cannot be canceled
# by varying only the two primary multipliers.

assert sp.diff(remaining,chiT) == -eps
assert remaining != 0

print("PASS: secondary off-shell obstruction",
      flush=True)

# On the full constraint surface the bulk
# expression vanishes, but this is weaker than
# off-shell action invariance.

weak = sp.simplify(
    bulk.subs({
        phiT:0,
        phiN:0,
        chiT:0
    })
)

assert weak == 0

print("PASS: weak vanishing distinguished",
      flush=True)

# No nonzero arbitrary epsilon can make the
# secondary coefficient identically vanish
# under the primary-only ansatz.
assert sp.solve(
    sp.Eq(coeff_chiT,0),eps
) == [0]

print("PASS: primary-only arbitrary gauge function rejected",
      flush=True)

print("PRIMARY-ONLY OFF-SHELL ACTION SYMMETRY: FAILS")
print("RESULT: SECONDARY GENERATOR TERMS REQUIRED")
print("FULL THREE-STAGE GENERATOR: OPEN")
print("MULTIPLIER TRANSFORMATIONS: OPEN")
print("SINGULAR SECTORS: OPEN")
print("PHYSICAL VALIDATION: NOT ESTABLISHED")
